"""Lucky colour & number of the day (五行 heuristic, deterministic per user + date).

* With a Day Master: the lucky element is the one that GENERATES the Day Master (印星,
  supportive) unless today's day-stem element already does; then it's the Day Master's own element.
* Without a profile: today's day-stem element.
Colours/numbers by element follow common 五行 associations (河图 numbers: 水1·6 火2·7 木3·8 金4·9 土5·10).
"""
from __future__ import annotations

import hashlib
from datetime import date

from .bazi import GAN_WX

GEN_BY = {"木": "水", "火": "木", "土": "火", "金": "土", "水": "金"}   # X is generated by GEN_BY[X]
COLORS = {
    "木": [("绿色", "зелёный", "green", "🟢"), ("青色", "бирюзовый", "teal", "🟢")],
    "火": [("红色", "красный", "red", "🔴"), ("紫色", "фиолетовый", "purple", "🟣")],
    "土": [("黄色", "жёлтый", "yellow", "🟡"), ("棕色", "коричневый", "brown", "🟤")],
    "金": [("白色", "белый", "white", "⚪"), ("金色", "золотой", "gold", "🟡")],
    "水": [("黑色", "чёрный", "black", "⚫"), ("蓝色", "синий", "blue", "🔵")],
}
NUMBERS = {"水": (1, 6), "火": (2, 7), "木": (3, 8), "金": (4, 9), "土": (5, 10)}
DIRECTIONS = {"木": ("东", "восток", "east"), "火": ("南", "юг", "south"), "土": ("中央", "центр", "centre"),
              "金": ("西", "запад", "west"), "水": ("北", "север", "north")}
_I = {"zh": 0, "ru": 1, "en": 2}


def lucky(uid: int, day: date, day_stem: str, day_master: str | None = None) -> dict:
    today = GAN_WX[day_stem]
    if day_master:
        dm = GAN_WX[day_master]
        el = GEN_BY[dm] if today != GEN_BY[dm] else dm
    else:
        el = today
    h = int(hashlib.sha256(f"{uid}:{day.isoformat()}".encode()).hexdigest(), 16)
    color = COLORS[el][h % 2]
    nums = NUMBERS[el]
    return {"element": el, "color": color, "numbers": [nums[h // 2 % 2], nums[1 - h // 2 % 2]],
            "direction": DIRECTIONS[el]}


def color_name(c, lang):
    return f"{c[3]} {c[_I.get(lang, 2)]}"


def direction_name(d, lang):
    return d[_I.get(lang, 2)]
